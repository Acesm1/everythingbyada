create table if not exists public.product_reviews (
  id bigint generated by default as identity primary key,
  order_id text not null references public.orders(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  rating integer not null check (rating between 1 and 5),
  review_text text not null check (char_length(btrim(review_text)) between 5 and 1200),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now(),
  unique (order_id, product_id)
);
alter table public.product_reviews enable row level security;
grant select on public.product_reviews to anon, authenticated;
grant insert, update on public.product_reviews to authenticated;
drop policy if exists "Public can read approved product reviews" on public.product_reviews;
create policy "Public can read approved product reviews" on public.product_reviews
  for select to anon, authenticated using (status = 'approved');
drop policy if exists "Customers can read their own product reviews" on public.product_reviews;
create policy "Customers can read their own product reviews" on public.product_reviews
  for select to authenticated using (user_id = (select auth.uid()));
drop policy if exists "Customers review products from accepted orders" on public.product_reviews;
create policy "Customers review products from accepted orders" on public.product_reviews
  for insert to authenticated with check (
    user_id = (select auth.uid())
    and status = 'pending'
    and exists (
      select 1
      from public.orders o
      cross join lateral jsonb_array_elements(coalesce(o.items, '[]'::jsonb)) as order_item(item)
      where o.id = product_reviews.order_id
        and o.user_id = (select auth.uid())
        and o.status = 'Accepted'
        and order_item.item ->> 'product_id' = product_reviews.product_id::text
    )
  );
drop policy if exists "Customers can resubmit rejected product reviews" on public.product_reviews;
create policy "Customers can resubmit rejected product reviews" on public.product_reviews
  for update to authenticated using (
    user_id = (select auth.uid()) and status = 'rejected'
  ) with check (
    user_id = (select auth.uid())
    and status = 'pending'
    and exists (
      select 1
      from public.orders o
      cross join lateral jsonb_array_elements(coalesce(o.items, '[]'::jsonb)) as order_item(item)
      where o.id = product_reviews.order_id
        and o.user_id = (select auth.uid())
        and o.status = 'Accepted'
        and order_item.item ->> 'product_id' = product_reviews.product_id::text
    )
  );
drop policy if exists "Admins manage product reviews" on public.product_reviews;
create policy "Admins manage product reviews" on public.product_reviews
  for all to authenticated using (public.is_admin()) with check (public.is_admin());
