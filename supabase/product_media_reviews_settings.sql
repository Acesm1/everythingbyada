-- Run once in Supabase SQL Editor to enable product videos, customer reviews,
-- review moderation, and the admin store-settings screen.

alter table public.products
  add column if not exists video_urls jsonb not null default '[]'::jsonb;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'product-videos',
  'product-videos',
  true,
  157286400,
  array['video/mp4', 'video/webm', 'video/quicktime']
)
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Product videos are publicly readable" on storage.objects;
create policy "Product videos are publicly readable"
  on storage.objects for select using (bucket_id = 'product-videos');
drop policy if exists "Admins upload product videos" on storage.objects;
create policy "Admins upload product videos"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'product-videos' and public.is_admin());
drop policy if exists "Admins update product videos" on storage.objects;
create policy "Admins update product videos"
  on storage.objects for update to authenticated
  using (bucket_id = 'product-videos' and public.is_admin())
  with check (bucket_id = 'product-videos' and public.is_admin());
drop policy if exists "Admins delete product videos" on storage.objects;
create policy "Admins delete product videos"
  on storage.objects for delete to authenticated
  using (bucket_id = 'product-videos' and public.is_admin());

create table if not exists public.store_settings (
  id bigint generated by default as identity primary key,
  key text not null unique,
  value text not null,
  updated_at timestamptz not null default now()
);
do $$
declare
  id_sequence text;
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public'
      and table_name = 'store_settings'
      and column_name = 'id'
      and is_identity = 'NO'
      and column_default is null
  ) then
    alter table public.store_settings alter column id add generated by default as identity;
  end if;

  id_sequence := pg_get_serial_sequence('public.store_settings', 'id');
  if id_sequence is not null then
    perform setval(id_sequence::regclass, coalesce((select max(id) from public.store_settings), 0) + 1, false);
  end if;
end
$$;
alter table public.store_settings add column if not exists updated_at timestamptz not null default now();
alter table public.store_settings enable row level security;
grant select, insert, update on public.store_settings to authenticated;
revoke all on public.store_settings from anon;
drop policy if exists "Admins manage store settings" on public.store_settings;
create policy "Admins manage store settings" on public.store_settings
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

