-- Schema for restoring Everything By Ada table exports to a fresh self-hosted
-- Supabase instance. This intentionally does not insert demo catalog records.

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  price numeric not null default 0,
  old_price numeric not null default 0,
  stock integer not null default 0,
  image text not null default '',
  feature text not null default '',
  description text not null default '',
  rating numeric not null default 4.8,
  reviews integer not null default 0,
  video_urls jsonb not null default '[]'::jsonb,
  best_seller boolean not null default false,
  created_at timestamptz not null default now()
);
alter table public.products add column if not exists video_urls jsonb not null default '[]'::jsonb;

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text unique not null,
  is_special boolean not null default false,
  image_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.customer_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  phone text,
  address text,
  city text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id text primary key,
  user_id uuid references auth.users(id) on delete set null,
  customer_name text,
  customer_email text,
  total numeric not null default 0,
  status text not null default 'Pending',
  items jsonb not null default '[]'::jsonb,
  payment_reference text,
  receipt_path text,
  delivery_full_name text,
  delivery_phone text,
  delivery_address text,
  delivery_city text,
  delivery_state text,
  delivery_postal_code text,
  delivery_notes text,
  created_at timestamptz not null default now()
);

create table if not exists public.product_reviews (
  id bigint generated by default as identity primary key,
  order_id text not null references public.orders(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  rating integer not null check (rating between 1 and 5),
  review_text text not null check (char_length(btrim(review_text)) between 5 and 1200),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now(),
  unique (order_id, product_id)
);

create unique index if not exists orders_payment_reference_unique
  on public.orders (payment_reference)
  where payment_reference is not null;

create table if not exists public.carts (
  user_id uuid primary key references auth.users(id) on delete cascade,
  items jsonb not null default '[]'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.store_settings (
  id bigint generated by default as identity primary key,
  key text not null unique,
  value text not null,
  updated_at timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admin_users
    where user_id = (select auth.uid())
  );
$$;

do $$
declare
  id_sequence text;
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public'
      and table_name = 'store_settings'
      and column_name = 'id'
      and is_identity = 'NO'
      and column_default is null
  ) then
    alter table public.store_settings alter column id add generated by default as identity;
  end if;

  id_sequence := pg_get_serial_sequence('public.store_settings', 'id');
  if id_sequence is not null then
    perform setval(id_sequence::regclass, coalesce((select max(id) from public.store_settings), 0) + 1, false);
  end if;
end
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.customer_profiles (id, full_name, phone, address, city)
  values (
    new.id,
    new.raw_user_meta_data ->> 'full_name',
    new.raw_user_meta_data ->> 'phone',
    new.raw_user_meta_data ->> 'address',
    new.raw_user_meta_data ->> 'city'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

