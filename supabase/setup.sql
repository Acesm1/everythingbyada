create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  price numeric not null default 0,
  old_price numeric not null default 0,
  stock integer not null default 0,
  image text not null default '',
  feature text not null default '',
  description text not null default '',
  rating numeric not null default 4.8,
  reviews integer not null default 0,
  created_at timestamptz not null default now()
);
alter table public.products add column if not exists description text not null default '';
alter table public.products enable row level security;
grant select on public.products to anon, authenticated;
grant insert, update, delete on public.products to authenticated;
drop policy if exists "Catalog is readable by everyone" on public.products;
create policy "Catalog is readable by everyone" on public.products for select to anon, authenticated using (true);
drop policy if exists "Admins manage products" on public.products;
create policy "Admins manage products" on public.products for all to authenticated using (public.is_admin()) with check (public.is_admin());

