create table if not exists public.customer_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  phone text,
  address text,
  city text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.customer_profiles enable row level security;
grant select, insert, update on public.customer_profiles to authenticated;
drop policy if exists "Users can view their own profile" on public.customer_profiles;
create policy "Users can view their own profile" on public.customer_profiles for select to authenticated using ((select auth.uid()) = id);
drop policy if exists "Users can insert their own profile" on public.customer_profiles;
create policy "Users can insert their own profile" on public.customer_profiles for insert to authenticated with check ((select auth.uid()) = id);
drop policy if exists "Users can update their own profile" on public.customer_profiles;
create policy "Users can update their own profile" on public.customer_profiles for update to authenticated using ((select auth.uid()) = id) with check ((select auth.uid()) = id);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.admin_users enable row level security;
grant select on public.admin_users to authenticated;
revoke insert, update, delete on public.admin_users from anon, authenticated;
drop policy if exists "Users can see their own admin status" on public.admin_users;
create policy "Users can see their own admin status" on public.admin_users for select to authenticated using ((select auth.uid()) = user_id);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.admin_users where user_id = (select auth.uid()));
$$;
grant execute on function public.is_admin() to authenticated;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.customer_profiles (id, full_name, phone, address, city)
  values (
    new.id,
    new.raw_user_meta_data ->> 'full_name',
    new.raw_user_meta_data ->> 'phone',
    new.raw_user_meta_data ->> 'address',
    new.raw_user_meta_data ->> 'city'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

create table if not exists public.orders (
  id text primary key,
  user_id uuid references auth.users(id) on delete set null,
  customer_name text,
  customer_email text,
  total numeric not null default 0,
  status text not null default 'Pending',
  items jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);
alter table public.orders add column if not exists user_id uuid references auth.users(id) on delete set null;
alter table public.orders add column if not exists items jsonb not null default '[]'::jsonb;
alter table public.orders enable row level security;
grant select, insert, update on public.orders to authenticated;
drop policy if exists "Customers create their own orders" on public.orders;
create policy "Customers create their own orders" on public.orders for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists "Customers and admins view orders" on public.orders;
create policy "Customers and admins view orders" on public.orders for select to authenticated using ((select auth.uid()) = user_id or public.is_admin());
drop policy if exists "Admins update orders" on public.orders;
create policy "Admins update orders" on public.orders for update to authenticated using (public.is_admin()) with check (public.is_admin());

